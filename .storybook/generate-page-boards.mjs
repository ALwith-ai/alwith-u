const ignoredControlArgs = new Set(["page", "authenticated", "binaryFiles", "height"])

function storyBlocks(source) {
  const declarations = [...source.matchAll(/^export const\s+(\w+)/gm)]
  return new Map(
    declarations.map((declaration, index) => [
      declaration[1],
      source.slice(declaration.index, declarations[index + 1]?.index)
    ])
  )
}

function storyLabel(source, name) {
  const block = storyBlocks(source).get(name) ?? ""
  const explicit = block.match(/\bname:\s*(["'])(.*?)\1/)
  return explicit?.[2] ?? name.replace(/([a-z])([A-Z])/g, "$1 $2")
}

function caseGroups(source, order) {
  const blocks = storyBlocks(source)
  const groupFor = (name, visited = new Set()) => {
    if (visited.has(name)) return "页面状态"
    visited.add(name)
    const block = blocks.get(name) ?? ""
    const explicit = block.match(/pageStateGroup:\s*(["'])(.*?)\1/)
    if (explicit) return explicit[2]
    const args = block.match(/\bargs:\s*\{([\s\S]*?)\}/)?.[1] ?? ""
    const key = args.match(/\b(\w+)\s*:/)?.[1]
    if (key && !ignoredControlArgs.has(key)) return controlLabels[key] ?? "页面状态"
    const inherited = block.match(/\.\.\.(\w+)/)?.[1]
    if (inherited) return groupFor(inherited, visited)
    if (/\bglobals:\s*\{/.test(block)) return "显示模式"
    return /\bplay:\s*async/.test(block) ? "页面操作" : "默认状态"
  }
  const groups = new Map()
  for (const name of order) {
    const label = groupFor(name)
    const group = groups.get(label) ?? { label, cases: [] }
    group.cases.push(name)
    groups.set(label, group)
  }
  return [...groups.values()]
}

await mkdir(boards, { recursive: true })
for (const filename of (await readdir(pages)).filter((name) => name.endsWith(".stories.tsx")).sort()) {
  const source = await readFile(path.join(pages, filename), "utf8")
  const metaSource = source.slice(source.indexOf("const meta"))
  const sourceTitle = metaSource.match(/\btitle:\s*(["'])(.*?)\1/)?.[2]
  const title = sourceTitle?.replace(/\/页面状态$/, "")
  if (!title) throw new Error(`A static title is required for ${filename}`)
  const pageId = filename.replace(/\.stories\.tsx$/, "")
  const order = [...source.matchAll(/^export const\s+(\w+)/gm)].map((match) => match[1])
  const groups = caseGroups(source, order)
  for (const [index, group] of groups.entries()) {
    const groupFilename = `${pageId}-${index + 1}.stories.tsx`
    const id = `page-${pageId}-${index + 1}`
    const stories = group.cases
      .map((name) => `export const ${name} = { ...source.${name}, name: ${JSON.stringify(storyLabel(source, name))} }`)
      .join("\n")
    const output = `// Generated by .storybook/generate-page-boards.mjs from the source page stories.\nimport * as source from "../pages/${filename}"\n\nconst meta = {\n  ...source.default,\n  id: ${JSON.stringify(id)},\n  title: ${JSON.stringify(`${title}/${group.label}`)}\n}\nexport default meta\n\n${stories}\n`
    const file = path.join(boards, groupFilename)
    await writeFile(file, output)
    emitted.add(file)
  }
}
for (const filename of await readdir(boards)) {
  const file = path.join(boards, filename)
  if (
    !emitted.has(file) &&
    (await readFile(file, "utf8")).startsWith("// Generated by .storybook/generate-page-boards.mjs")
  )
    await rm(file)
}
console.log(`${emitted.size} page feature story files generated`)
